--   COMMIT, y eso solo es legal si el CALL no viene en una transacción.
--
-- ---------------------------------------------------------------------------
-- QUÉ ARREGLA
-- ---------------------------------------------------------------------------
-- La carga masiva escribió el ciclo de 9 tablas del pedido pero NUNCA creó
-- envíos: `envio` tenía 2.872 filas y terminaba el 2026-07-23. Los tableros
-- T-4 (Operación y Última Milla) y T-5 (Costo de la Operación) se apoyan en
-- `fact_envio`, así que su serie se cortaba en 19 meses mientras el resto de
-- la casa llegaba a 2034 — sin error y sin explicación en pantalla.
--
-- Esta fase NO TOCA STOCK. Los envíos cuelgan de pedidos que ya existen y que
-- ya movieron su kardex; aquí no se escribe ni una fila de
-- `movimiento_inventario` ni de `inventario`.
--
-- ---------------------------------------------------------------------------
-- LA REGLA: QUÉ PEDIDOS LLEVAN ENVÍO — derivada, no inventada
-- ---------------------------------------------------------------------------
-- Medido sobre los 4.083 pedidos originales, cruzando estado y canal:
--
--   por ESTADO          pedidos  con envío        por CANAL   pedidos  con envío
--   entregado             3.592     73,7 %        web           2.082    100,0 %
--   despachado               16    100,0 %        telefono        778    100,0 %
--   no_entregado            122    100,0 %        tienda          981      1,2 %
--   devuelto                111     78,4 %
--   los otros seis            —      0,0 %
--
-- El «73,7 % de los entregados» NO es azar: es que **la compra en tienda se
-- retira en tienda**. Cruzando las dos dimensiones la regla sale limpia:
--
--     lleva envío  ⇔  estado ∈ {entregado, despachado, no_entregado, devuelto}
--                     Y  canal ≠ 'tienda'
--
-- y con ella los 2.860 pedidos web/teléfono de esos estados tienen los 2.860
-- envíos. Los 12 envíos de pedidos 'tienda' que hay en el seed son ruido
-- (1,2 %) y no se reproducen: un patrón del 1 % no es un patrón.
-- Coherente además con el dinero: `pedido.costo_envio = 0` en los 1.030
-- pedidos de tienda, y ninguno trae transportista ni método de envío.
--
-- ---------------------------------------------------------------------------
-- COHERENCIA CON EL ESTADO DEL PEDIDO — también medida
-- ---------------------------------------------------------------------------
--   pedido despachado    → envío en_transito   (16/16)
--   pedido entregado     → envío entregado     (2.647/2.647)
--   pedido no_entregado  → envío devuelto      (121) · en_transito (1)
--   pedido devuelto      → envío entregado     (80)  · en_transito (7)
--
-- Se reproduce el caso dominante de cada estado. Los residuos de un solo
-- dígito no se imitan.
--
-- LAS FECHAS NO SE INVENTAN: SE LEEN DE `historial_estado_pedido`. Cada pedido
-- ya tiene ahí el instante exacto en que pasó por 'despachado' y por
-- 'entregado'. Derivarlas de ahí hace imposible que un envío se despache antes
-- que su pedido o que entregue antes de despachar — la coherencia temporal no
-- se comprueba después, sale por construcción.
--
-- EL COSTO SALE DEL PEDIDO. Medido: 2.871 de los 2.872 envíos cumplen
-- `envio.costo = pedido.costo_envio` (el que falta es legacy). Se copia, con
-- lo que el invariante queda al 100 % en lo nuevo.
--
-- ---------------------------------------------------------------------------
-- TRAMOS RESERVADOS
-- ---------------------------------------------------------------------------
-- IDs — el techo real NO es el `bigint` de PostgreSQL: es el **UInt32** del
-- almacén (4.294.967.295). `fact_envio.envio_id` y `fact_novedad_envio`
-- (`novedad_id`, `envio_id`, `pedido_id`) son UInt32; `seguimiento_envio` y
-- `envio_detalle` no viajan al DWH.
--
--     envio              2.200.000.000   (2,11 M → tope 2.202,2 M)
--     envio_detalle      2.300.000.000
--     seguimiento_envio  2.400.000.000   (6,3 M  → tope 2.406,3 M)
--     novedad_envio      2.500.000.000
--
-- El id más alto queda en ~2.406 M, al **56 %** del techo UInt32.
-- `novedad_envio.id` es GENERATED BY DEFAULT y no necesita OVERRIDING; los
-- otros tres son GENERATED ALWAYS y sí.
--
-- NÚMEROS DE DOCUMENTO — `envio.numero` es UNIQUE, formato `EN-YYYYMMDD-NNNNNN`
-- con SEIS dígitos en el seed (101412..112019). La banda nueva usa **SIETE
-- dígitos desde 5.000.000**, y ninguna cadena de seis puede igualar a una de
-- siete. `numero_guia` (no único) usa la misma secuencia.
-- La Fase 3 aprendió por qué esto no se razona sino que se COMPRUEBA: allí la
-- banda «única por fase» falló porque el número lleva la fecha y las ventanas
-- de documento sobresalen por los bordes (183 choques). Aquí hay un guardia
-- que compara los números generados contra los existentes ANTES de escribir.
--
-- IDEMPOTENTE (ON CONFLICT DO NOTHING) · POR LOTES CON COMMIT
