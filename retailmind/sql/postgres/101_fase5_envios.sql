-- 0. AZAR DETERMINISTA · GUARDIA DEL TRAMO
-- ════════════════════════════════════════════════════════════════════════════
CREATE OR REPLACE FUNCTION pg_temp.u(k text, i bigint) RETURNS numeric
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
$$ SELECT ((('x' || substr(md5('f5' || k || i::text), 1, 7))::bit(28)::int)
           % 1000000)::numeric / 1000000.0 $$;

CREATE TEMP TABLE f5_medicion(paso text, lote int, inicio timestamptz,
                              fin timestamptz, filas bigint);
CREATE OR REPLACE PROCEDURE pg_temp.medir(p text, l int, i timestamptz, f bigint)
LANGUAGE sql AS
$$ INSERT INTO f5_medicion VALUES (p, l, i, clock_timestamp(), f) $$;

DO $guardia$
DECLARE n bigint; sucias text := '';
        v_re int := current_setting('retailmind.reanudar', true)::int;
BEGIN
    SELECT count(*) INTO n FROM envio             WHERE id >= 2200000000;
    IF n > 0 THEN sucias := sucias || format('  envio: %s%s', n, E'\n'); END IF;
    SELECT count(*) INTO n FROM envio_detalle     WHERE id >= 2300000000;
    IF n > 0 THEN sucias := sucias || format('  envio_detalle: %s%s', n, E'\n'); END IF;
    SELECT count(*) INTO n FROM seguimiento_envio WHERE id >= 2400000000;
    IF n > 0 THEN sucias := sucias || format('  seguimiento_envio: %s%s', n, E'\n'); END IF;
    SELECT count(*) INTO n FROM novedad_envio     WHERE id >= 2500000000;
    IF n > 0 THEN sucias := sucias || format('  novedad_envio: %s%s', n, E'\n'); END IF;

    IF sucias <> '' AND v_re = 0 THEN
        RAISE EXCEPTION 'Los tramos de la Fase 5 YA tienen filas. Revierte con '
                        '99_revert_fase5.sql o reanuda con -v reanudar=1:%', E'\n' || sucias;
    ELSIF sucias <> '' THEN
        RAISE NOTICE 'REANUDANDO sobre una carga incompleta:%', E'\n' || sucias;
    ELSE
        RAISE NOTICE 'Guardia OK: los cuatro tramos estan vacios.';
    END IF;
END
$guardia$;

-- ════════════════════════════════════════════════════════════════════════════
-- 1. EL PLAN: un envío por pedido elegible, con sus fechas LEÍDAS del historial
-- ════════════════════════════════════════════════════════════════════════════
CREATE TEMP TABLE f5_env AS
WITH elegible AS (
    SELECT p.id AS pedido_id, p.canal, p.costo_envio, p.transportista_id,
           p.metodo_envio_id, p.direccion_envio_id, p.fecha_pedido,
           ep.codigo AS estado_pedido,
           row_number() OVER (ORDER BY p.id) AS n
    FROM pedido p
    JOIN estado_pedido ep ON ep.id = p.estado_pedido_id
    WHERE p.canal <> 'tienda'
      AND ep.codigo IN ('entregado', 'despachado', 'no_entregado', 'devuelto')
      AND NOT EXISTS (SELECT 1 FROM envio e WHERE e.pedido_id = p.id)
),
-- Las fechas salen de los hitos que el pedido YA tiene. `min` y no `max`
-- porque un pedido puede tener el hito repetido (19 'confirmado', 8 'pagado'
-- y 5 'despachado' duplicados en el seed original).
hitos AS (
    SELECT h.pedido_id,
           min(h.fecha_creacion) FILTER (WHERE ep.codigo = 'despachado') AS f_desp,
           min(h.fecha_creacion) FILTER (WHERE ep.codigo = 'entregado')  AS f_ent
    FROM historial_estado_pedido h
    JOIN estado_pedido ep ON ep.id = h.estado_pedido_id
    WHERE ep.codigo IN ('despachado', 'entregado')
      AND EXISTS (SELECT 1 FROM elegible el WHERE el.pedido_id = h.pedido_id)
    GROUP BY h.pedido_id
),
peso AS (
    SELECT pd.pedido_id, sum(pd.cantidad * COALESCE(pv.peso_kg, 0))::numeric(8,3) AS kg
    FROM pedido_detalle pd
    JOIN producto_variante pv ON pv.id = pd.producto_variante_id
    WHERE EXISTS (SELECT 1 FROM elegible el WHERE el.pedido_id = pd.pedido_id)
    GROUP BY pd.pedido_id
)
SELECT
    2200000000 + e.n              AS id,
    e.n,
    e.pedido_id,
    e.estado_pedido,
    e.costo_envio                 AS costo,
    e.transportista_id,
    e.metodo_envio_id,
    LEAST(COALESCE(pe.kg, 0), 99999.999)::numeric(8,3) AS peso_total_kg,
    -- Estado del envío: el caso dominante medido para cada estado de pedido.
    CASE e.estado_pedido
        WHEN 'despachado'   THEN 'en_transito'
        WHEN 'entregado'    THEN 'entregado'
        WHEN 'no_entregado' THEN 'devuelto'
        WHEN 'devuelto'     THEN 'entregado'
    END                           AS estado,
    -- Despacho: el hito real. Si faltara, se ancla al pedido + la media medida
    -- (1,74 días) para no dejar NULL en un envío que sí salió.
    COALESCE(h.f_desp, e.fecha_pedido + interval '1.74 days') AS fecha_despacho,
    -- Entrega real: solo si el envío acabó entregado.
    CASE WHEN e.estado_pedido IN ('entregado', 'devuelto')
         THEN COALESCE(h.f_ent, COALESCE(h.f_desp, e.fecha_pedido) + interval '3.67 days')
    END                           AS fecha_entrega_real,
    e.direccion_envio_id,
    e.fecha_pedido
FROM elegible e
LEFT JOIN hitos h ON h.pedido_id = e.pedido_id
LEFT JOIN peso  pe ON pe.pedido_id = e.pedido_id;

CREATE UNIQUE INDEX ON f5_env(id);
CREATE INDEX ON f5_env(pedido_id);

-- Promesa de entrega: la media medida es 3,36 días sobre el despacho.
ALTER TABLE f5_env ADD COLUMN fecha_entrega_estimada date,
                   ADD COLUMN numero text, ADD COLUMN guia text,
                   ADD COLUMN lote int, ADD COLUMN direccion text;
UPDATE f5_env f SET
    fecha_entrega_estimada = (f.fecha_despacho + ((2 + floor(pg_temp.u('pr', f.n) * 4)) || ' days')::interval)::date,
    numero = 'EN-'   || to_char(f.fecha_despacho AT TIME ZONE 'America/Guayaquil', 'YYYYMMDD')
                     || '-' || lpad((5000000 + f.n)::text, 7, '0'),
    guia   = 'GUIA-' || to_char(f.fecha_despacho AT TIME ZONE 'America/Guayaquil', 'YYYYMMDD')
                     || '-' || lpad((5000000 + f.n)::text, 7, '0'),
    lote   = ((f.n - 1) / 250000)::int + 1;

UPDATE f5_env f SET direccion = COALESCE(
    (SELECT left(d.calle_principal || ', ' || ci.nombre, 400)
       FROM direccion d JOIN ciudad ci ON ci.id = d.ciudad_id
      WHERE d.id = f.direccion_envio_id), 'Direccion no registrada');

\echo '--- 1. Plan de envios construido ---'
SELECT count(*) AS envios_a_cargar, count(DISTINCT lote) AS lotes,
       min(fecha_despacho)::date AS primer_despacho,
       max(fecha_despacho)::date AS ultimo_despacho
FROM f5_env;

-- ════════════════════════════════════════════════════════════════════════════
-- 2. GUARDIAS ANTES DE ESCRIBIR
-- ════════════════════════════════════════════════════════════════════════════
DO $guardias$
DECLARE v int; v_txt text;
BEGIN
    -- (1) Ninguna fecha por delante de su pedido, y los hitos en orden.
    SELECT count(*) INTO v FROM f5_env
    WHERE fecha_despacho < fecha_pedido
       OR (fecha_entrega_real IS NOT NULL AND fecha_entrega_real < fecha_despacho);
    IF v > 0 THEN
        RAISE EXCEPTION 'ABORTA: % envios con fechas incoherentes con su pedido.', v;
    END IF;

    -- (2) Ningun envio de un pedido cancelado o no despachable.
    SELECT count(*) INTO v FROM f5_env f JOIN pedido p ON p.id = f.pedido_id
    JOIN estado_pedido ep ON ep.id = p.estado_pedido_id
    WHERE p.canal = 'tienda'
       OR ep.codigo NOT IN ('entregado','despachado','no_entregado','devuelto');
    IF v > 0 THEN RAISE EXCEPTION 'ABORTA: % envios de pedidos no elegibles.', v; END IF;

    -- (3) El costo tiene que ser el del pedido, sin excepcion.
    SELECT count(*) INTO v FROM f5_env f JOIN pedido p ON p.id = f.pedido_id
    WHERE f.costo <> p.costo_envio;
    IF v > 0 THEN RAISE EXCEPTION 'ABORTA: % envios con costo distinto al del pedido.', v; END IF;

    -- (4) NUMEROS DE DOCUMENTO: se comparan, no se razonan. La Fase 3 aprendio
    --     que el numero lleva la fecha y sobresale de la ventana del bloque.
    SELECT count(*), left(string_agg(DISTINCT n, ', '), 120) INTO v, v_txt
    FROM (SELECT e.numero AS n FROM envio e
          JOIN (SELECT DISTINCT numero FROM f5_env) g ON g.numero = e.numero) z;
    IF v > 0 THEN
        RAISE EXCEPTION 'ABORTA: % numeros de envio CHOCAN con los existentes (%).', v, v_txt;
    END IF;

    RAISE NOTICE 'Guardias OK: fechas coherentes, elegibilidad, costo y 0 choques de numero.';
END
$guardias$;

-- ════════════════════════════════════════════════════════════════════════════
-- 3. CARGA POR LOTES DE 250.000 ENVIOS
-- ════════════════════════════════════════════════════════════════════════════
CREATE OR REPLACE PROCEDURE pg_temp.cargar()
LANGUAGE plpgsql AS $carga$
DECLARE v_lote int; v_tot int; v_ini timestamptz; v_n bigint;
BEGIN
SELECT max(lote) INTO v_tot FROM f5_env;
FOR v_lote IN 1..v_tot LOOP

    v_ini := clock_timestamp();
    INSERT INTO envio (id, numero, pedido_id, transportista_id, metodo_envio_id, bodega_id,
                       direccion_entrega, numero_guia, estado, costo, peso_total_kg,
                       fecha_despacho, fecha_entrega_estimada, fecha_entrega_real,
                       fecha_creacion, despachado_por)
    OVERRIDING SYSTEM VALUE
    SELECT f.id, f.numero, f.pedido_id, f.transportista_id, f.metodo_envio_id, 4,
           f.direccion, f.guia, f.estado, f.costo, f.peso_total_kg,
           f.fecha_despacho, f.fecha_entrega_estimada, f.fecha_entrega_real,
           f.fecha_despacho, 10
    FROM f5_env f WHERE f.lote = v_lote
    ON CONFLICT (id) DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT; CALL pg_temp.medir('envio', v_lote, v_ini, v_n);

    -- Seguimiento: el rastro que el cliente ve. Medido 2,99 eventos por envio.
    v_ini := clock_timestamp();
    INSERT INTO seguimiento_envio (id, envio_id, estado, descripcion, ubicacion,
                                   fecha_evento, fecha_creacion)
    OVERRIDING SYSTEM VALUE
    SELECT 2400000000 + (f.n - 1) * 3 + x.k, f.id, x.estado, x.descripcion, x.ubicacion,
           x.ts, x.ts
    FROM f5_env f
    CROSS JOIN LATERAL (VALUES
        (1, 'despachado',  'Paquete despachado desde bodega', 'Quevedo, Los Rios',
            f.fecha_despacho),
        (2, 'en_transito', 'En ruta hacia el destino',        'En transito',
            f.fecha_despacho + interval '8 hours'),
        (3, CASE f.estado WHEN 'entregado' THEN 'entregado'
                          WHEN 'devuelto'  THEN 'devuelto' END,
            CASE f.estado WHEN 'entregado' THEN 'Entregado al destinatario'
                          WHEN 'devuelto'  THEN 'Devuelto al almacen tras intento fallido' END,
            'Destino',
            CASE f.estado WHEN 'entregado' THEN f.fecha_entrega_real
                          WHEN 'devuelto'  THEN f.fecha_despacho + interval '5 days' END)
    ) x(k, estado, descripcion, ubicacion, ts)
    WHERE f.lote = v_lote AND x.estado IS NOT NULL AND x.ts IS NOT NULL
    ON CONFLICT (id) DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT; CALL pg_temp.medir('seguimiento_envio', v_lote, v_ini, v_n);

    -- Novedad: solo en el camino que la justifica — el pedido no se entrego y
    -- el envio volvio al almacen. Es el flujo documentado del script 44.
    v_ini := clock_timestamp();
    INSERT INTO novedad_envio (id, envio_id, pedido_id, tipo, descripcion, intento_numero,
                               estado, accion, registrado_por, resuelto_por,
                               fecha_registro, fecha_resolucion)
    OVERRIDING SYSTEM VALUE
    SELECT 2500000000 + f.n, f.id, f.pedido_id,
           (ARRAY['cliente_ausente','direccion_incorrecta','cliente_rechazo',
                  'zona_dificil_acceso','dano_en_transito'])
               [1 + floor(pg_temp.u('tp', f.n) * 5)::int],
           'Incidencia registrada en el intento de entrega', 1,
           'resuelta', 'devuelto_almacen', 10, 10,
           f.fecha_despacho + interval '3 days',
           f.fecha_despacho + interval '5 days'
    FROM f5_env f WHERE f.lote = v_lote AND f.estado = 'devuelto'
    ON CONFLICT (id) DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT; CALL pg_temp.medir('novedad_envio', v_lote, v_ini, v_n);

    -- `envio_detalle` es VESTIGIAL en este sistema: 29 filas para 2.872 envios
    -- (1,0 %). No alimenta ninguna tabla del almacen ni ningun informe. Se
    -- reproduce su tasa medida y NO se fabrican 2,4 M de filas de un patron
    -- que el dato original no tiene.
    v_ini := clock_timestamp();
    INSERT INTO envio_detalle (id, envio_id, pedido_detalle_id, cantidad, fecha_creacion)
    OVERRIDING SYSTEM VALUE
    SELECT 2300000000 + f.n, f.id, pd.id, pd.cantidad, f.fecha_despacho
    FROM f5_env f
    JOIN LATERAL (SELECT id, cantidad FROM pedido_detalle
                   WHERE pedido_id = f.pedido_id ORDER BY id LIMIT 1) pd ON true
    WHERE f.lote = v_lote AND pg_temp.u('det', f.n) < 0.010
    ON CONFLICT (id) DO NOTHING;
    GET DIAGNOSTICS v_n = ROW_COUNT; CALL pg_temp.medir('envio_detalle', v_lote, v_ini, v_n);

    COMMIT;
    RAISE NOTICE 'Lote %/% commiteado.', v_lote, v_tot;
END LOOP;
END
$carga$;
CALL pg_temp.cargar();

\echo '--- 3. Envios cargados ---'

