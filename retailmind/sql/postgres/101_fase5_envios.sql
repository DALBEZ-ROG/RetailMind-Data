SELECT (SELECT count(*) FROM envio)             AS envios_total,
       (SELECT count(*) FROM envio_detalle)     AS detalle_total,
       (SELECT count(*) FROM seguimiento_envio) AS seguimiento_total,
       (SELECT count(*) FROM novedad_envio)     AS novedades_total;
